async (page) => {
  const dir='/home/yukino/projects/work/cvte/cdn-hotspot-predictor/output/20261021_历史看板开发联调_v01';
  const dataset='ds_3c527ca3b91b481adf2b64f1090650b97b493a70504a8168706abebe097388cf';
  const real='ds_a2740c2769b0e4e56d95c5a6f7022457391aa48479b1eed8c3b00e231c057c3a';
  const checks=[],errors=[],queries=[],writes=[];
  const assert=(condition,message)=>{if(!condition)throw new Error(message);};
  page.on('pageerror',error=>errors.push(error.message));
  page.on('request',request=>{
    const url=new URL(request.url());
    if(url.pathname==='/api/history')queries.push(Object.fromEntries(url.searchParams));
    if((url.pathname.startsWith('/api/')||url.pathname.startsWith('/data-api/'))&&request.method()!=='GET')writes.push(request.method()+' '+url.pathname);
  });
  async function selectDataset(id,app) {
    await page.locator('.sidebar nav').getByRole('link',{name:'热点预测',exact:true}).click();
    await page.getByRole('button',{name:'接口数据 · 已有功能',exact:true}).click();
    await page.locator('.dataset-selection select').first().selectOption(id);
    await page.getByRole('combobox',{name:'业务 App',exact:true}).selectOption(app);
    await page.getByRole('button',{name:'使用所选数据集和 App',exact:true}).click();
    await page.locator('.sidebar nav').getByRole('link',{name:'业务总览',exact:true}).click();
    await page.locator('#history-app').waitFor();
  }
  const run=async()=>{
    const response=page.waitForResponse(r=>new URL(r.url()).pathname==='/api/history'&&r.status()===200);
    await page.getByRole('button',{name:'查询历史观测',exact:true}).click();
    const body=await (await response).json();
    await page.locator('.history-result-context').waitFor();
    return body;
  };
  await page.goto('http://localhost:5173/prediction#prediction');
  await selectDataset(dataset,'A');
  assert(await page.locator('#history-start').inputValue()==='2026-01-01','A start missing');
  await page.locator('#history-granularity').selectOption('WEEKLY');
  assert(await page.locator('#history-end').inputValue()==='2026-01-07','week end not fixed');
  assert(await page.locator('#history-end').getAttribute('readonly')!==null,'weekly end editable');
  const a=await run();
  assert(a.observedTrafficBytes==='10000000000000061','exact weekly total wrong');
  assert((await page.locator('.history-days tr[data-date="2026-01-02"]').innerText()).includes('0'),'explicit zero missing');
  assert((await page.locator('.history-days tr[data-date="2026-01-03"]').innerText()).includes('无观测（null）'),'gap became zero');
  assert((await page.locator('.history-ranking tbody').innerText()).includes('10000000000000001'),'table rounded byte precision');
  assert((await page.locator('.history-identity').innerText()).includes('FAKE'),'source label missing');
  assert(await page.locator('.overview-bottom').count()===0,'static mock mixed into API view');
  checks.push({name:'READY_selection_real_weekly_query_exact_bytes_null_zero_source',status:'PASSED'});
  await page.locator('.history-trend svg').hover({position:{x:100,y:100}});
  await page.locator('.history-trend .chart-tooltip').waitFor();
  assert((await page.locator('.history-trend .chart-tooltip').innerText()).includes('接口观测'),'chart source wrong');
  assert(!(await page.locator('.history-trend .chart-tooltip').innerText()).includes('UI Mock'),'chart falsely labels mock');
  await page.mouse.move(0,0);
  await page.screenshot({path:dir+'/20261021_历史周窗口_1920_v01.png',fullPage:true});
  await page.locator('#history-file').fill('a&b?#c');
  assert(await page.locator('.history-result-context').count()===0,'edited filters still show old result');
  const file=await run();
  assert(file.items.length===1&&file.items[0].fileKey==='a&b?#c','special exact fileKey mismatch');
  assert(file.days[3].observedTrafficBytes===null&&!file.missingDates.includes('2026-01-04'),'file gaps confused with App gaps');
  checks.push({name:'exact_fileKey_and_clear_stale_result',status:'PASSED'});
  await page.locator('#history-app').selectOption('B');
  assert(await page.locator('#history-file').inputValue()==='','old fileKey leaked across App');
  assert(await page.locator('.history-result-context').count()===0,'old App result retained');
  const b=await run();
  assert(b.appId==='B'&&b.observedTrafficBytes==='907','App B polluted');
  checks.push({name:'App_isolation_and_file_reset',status:'PASSED'});
  await page.locator('#history-app').selectOption('A');
  await page.locator('#history-granularity').selectOption('DAILY');
  await page.locator('#history-end').fill('2026-01-01');
  const day=await run();
  assert(day.days.length===1&&day.observedTrafficBytes==='10000000000000021','daily selection ignored');
  await page.locator('#history-topk').fill('1');
  const top=await run();
  assert(top.items.length===1,'topK ignored by backend');
  checks.push({name:'daily_date_and_topK_server_filters',status:'PASSED'});
  await page.locator('#history-start').fill('2026-01-08');
  await page.locator('#history-end').fill('2026-01-08');
  const empty=await run();
  assert(empty.observedTrafficBytes===null&&empty.items.length===0,'outside window manufactured traffic');
  assert((await page.locator('.history-ranking').innerText()).includes('没有匹配文件观测'),'empty state missing');
  checks.push({name:'unobserved_window_null_empty_state',status:'PASSED'});
  await page.locator('#history-start').fill('2026-01-09');
  const count=queries.length;
  await page.getByRole('button',{name:'查询历史观测',exact:true}).click();
  await page.getByRole('alert').filter({hasText:'历史查询失败'}).waitFor();
  assert(queries.length===count,'invalid date sent to backend');
  checks.push({name:'invalid_date_rejected_before_HTTP',status:'PASSED'});
  await page.getByRole('button',{name:'UI 演示',exact:true}).click();
  assert(await page.locator('.overview-bottom').count()===1,'UI demonstration removed');
  await page.getByRole('button',{name:'历史观测 · 接口数据',exact:true}).click();
  assert(await page.locator('.history-result-context').count()===0,'remounted panel reused old facts');
  checks.push({name:'UI_Mock_and_API_views_independent',status:'PASSED'});
  await selectDataset(real,'10350');
  await page.locator('#history-granularity').selectOption('WEEKLY');
  await page.locator('#history-start').fill('2026-10-07');
  const actual=await run();
  assert(actual.datasetSource==='REAL'&&actual.appId==='10350','REAL source lost');
  assert((await page.locator('.history-identity').innerText()).includes('REAL'),'REAL metadata hidden');
  await page.screenshot({path:dir+'/20261021_真实10350历史_v01.png',fullPage:true});
  checks.push({name:'existing_REAL_dataset_read_only_browser_query',status:'PASSED',bytes:actual.observedTrafficBytes});
  for(const width of [1366,1024]){
    await page.setViewportSize({width,height:900});
    const scroll=await page.evaluate(()=>document.documentElement.scrollWidth);
    assert(scroll<=width,'history page horizontal overflow '+width);
    checks.push({name:'responsive_'+width,status:'PASSED',scroll});
    if(width===1366)await page.screenshot({path:dir+'/20261021_历史看板_1366_v01.png',fullPage:true});
  }
  await page.setViewportSize({width:1920,height:1080});
  assert(errors.length===0,'runtime errors '+errors.join(';'));
  assert(writes.length===0,'unexpected writes '+writes.join(';'));
  return {status:'PASSED',checks,queries,runtimeErrors:errors,businessWrites:writes,note:'所有历史响应来自运行中的Python/Java，未使用HTTP替身。'};
}
